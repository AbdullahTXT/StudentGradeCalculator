#include <iostream>
using namespace std;

int main()
{
    cout << "Simple Calculator" << endl;

    int number1 = 20;
    int number2 = 5;

    cout << "Sum: "
         << number1 + number2 << endl;

    cout << "Difference: "
         << number1 - number2 << endl;

    cout << "Product: "
         << number1 * number2 << endl;

    cout << "Division: "
         << number1 / number2 << endl;

    return 0;
}